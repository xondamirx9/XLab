# Новый шаг схемы — новая строка в конце: (следующий номер, SQL). Сделанные шаги не правятся.
MIGRATIONS: tuple[tuple[int, str], ...] = (
    (1, SCHEMA_V1),
)

_MIGRATE_LOCK = 724_201_101          # номер блокировки: два сервера не меняют схему одновременно


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _migrate(conn: Conn) -> list[int]:
    conn.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATE_LOCK,))
    conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations ("
                 "version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())")
    done = {row["version"] for row in conn.execute("SELECT version FROM schema_migrations")}
    applied = []
    for version, sql in MIGRATIONS:
        if version in done:
            continue
        conn.execute(sql)                    # несколько команд без параметров — одним запросом
        conn.execute("INSERT INTO schema_migrations (version) VALUES (%s)", (version,))
        applied.append(version)
    return applied


class Database:
    """Пул соединений с PostgreSQL. Адрес — DATABASE_URL, например postgresql://codexlab:пароль@localhost/codexlab."""

    def __init__(self, url: str, *, max_size: int = 10) -> None:
        self._pool = ConnectionPool(url, min_size=1, max_size=max_size, open=False, timeout=30,
                                    kwargs={"row_factory": dict_row, "application_name": "codexlab"})

    async def open(self) -> list[int]:
        """Открывает пул и доводит схему до последней версии. Возвращает номера сделанных сейчас шагов."""
        await asyncio.to_thread(self._pool.open, wait=True, timeout=30)
        return await self.migrate()

    async def close(self) -> None:
        await asyncio.to_thread(self._pool.close)

    async def migrate(self) -> list[int]:
        return await self.run(_migrate)

    async def run(self, work: Callable[[Conn], T]) -> T:
        """Выполняет work(conn) одной транзакцией в отдельном потоке."""
        def call() -> T:
            with self._pool.connection() as conn:     # без ошибки — сохранить, с ошибкой — откатить
                return work(cast(Conn, conn))         # строки — словари: row_factory=dict_row в пуле
        return await asyncio.to_thread(call)


class PgStore:
    """Общая основа хранилищ: все они живут в одной базе."""

    def __init__(self, db: Database) -> None:
        self._db = db

    async def _run(self, work: Callable[[Conn], T]) -> T:
        return await self._db.run(work)

    async def init(self) -> None:
        """Схема общая для всех хранилищ; повторный вызов ничего не меняет."""
        await self._db.migrate()
